#!/usr/bin/env node
// Copies the repaired forge skill references into the hbf plugin skill, since a
// plugin file cannot point outside the plugin root (Claude Code plugin path
// rules: a component path that escapes the root does not load).
//
//   node tools/plugin/build.mjs          write plugin/hbf/skills/hbf/references/
//   node tools/plugin/build.mjs --check  exit 1 when a copy or an index drifted
//
// The absorbed skills are the forge skills PLAN v9.1 section 3.4 names; the
// datasheet-forge and hardware-diagrams text was folded into board-forge by
// R1-designs-reach-17 (D-576). A skill folder that git tracks under
// knowledge/references is copied to references/<skill>/ and committed. A folder
// or <skill>-SKILL.md that .gitignore keeps in the owner archive is copied, when
// it is on disk, to references/archive/, which plugin/hbf/.gitignore keeps out
// of git as well; a fresh checkout builds and checks the tracked part only.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { argv, exit, stdout } from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const SOURCE = "knowledge/references";
export const DEST = "plugin/hbf/skills/hbf/references";
export const ARCHIVE = "archive";
export const ABSORBED = ["print-forge", "board-forge"];

/** Every file below dir, as paths relative to dir, sorted. */
function walk(dir, base = dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, base, out);
    else out.push(relative(base, p));
  }
  return out;
}

/** Paths under SOURCE that git tracks, relative to SOURCE. */
function trackedSources(root) {
  const out = execFileSync("git", ["ls-files", "-z", "--", SOURCE], { cwd: root, encoding: "utf8" });
  return new Set(out.split("\0").filter(Boolean).map((p) => relative(SOURCE, p)));
}

const header = (src) => `<!-- generated by tools/plugin/build.mjs from ${SOURCE}/${src}; edit the source and rerun -->\n`;

/** The first heading of a markdown text, or its first line. */
function title(text) {
  const lines = text.split("\n");
  return (lines.find((l) => l.startsWith("# ")) ?? lines[0] ?? "").replace(/^# /, "").trim();
}

function index(heading, intro, rows) {
  const body = rows.map(({ path, text }) => `| ${path} | ${title(text)} | ${(text.match(/\n/g) ?? []).length} |`);
  return [`# ${heading}`, "", ...intro, "", "| file | title | lines (computed) |", "|---|---|---|", ...body, ""].join("\n");
}

/**
 * The files the plugin references folder should hold, as { relative path: text }.
 * archive is true when any owner archive source is on disk.
 */
export function expected(root = ROOT) {
  const tracked = trackedSources(root);
  const src = join(root, SOURCE);
  const files = new Map();
  const kept = [];
  const held = [];
  for (const skill of ABSORBED) {
    for (const rel of walk(join(src, skill)).filter((p) => p.endsWith(".md"))) {
      const from = `${skill}/${rel}`;
      const text = header(from) + readFileSync(join(src, from), "utf8");
      if (tracked.has(from)) kept.push({ path: from, text });
      else held.push({ path: `${ARCHIVE}/${from}`, text });
    }
    const skillFile = `${skill}-SKILL.md`;
    if (existsSync(join(src, skillFile)) && !tracked.has(skillFile)) {
      held.push({ path: `${ARCHIVE}/${skillFile}`, text: header(skillFile) + readFileSync(join(src, skillFile), "utf8") });
    }
  }
  for (const f of kept) files.set(f.path, f.text);
  files.set("INDEX.md", index("hbf skill references", [
    "Generated by tools/plugin/build.mjs; do not edit. Each file is a copy of the",
    `${SOURCE}/ file of the same path with one provenance line on top.`,
    `The owner archive copies (board-forge, datasheet intake, doc figures, the forge SKILL.md files)`,
    `are built into ${ARCHIVE}/ only where that archive is on disk, and are never committed (D-576).`,
  ], kept));
  if (held.length > 0) {
    for (const f of held) files.set(f.path, f.text);
    files.set(`${ARCHIVE}/INDEX.md`, index("hbf skill references, owner archive", [
      "Generated by tools/plugin/build.mjs from the owner archive copies on this disk; kept out of git.",
    ], held.map((f) => ({ ...f, path: f.path.slice(ARCHIVE.length + 1) }))));
  }
  return { files, archive: held.length > 0 };
}

/** Drift between the expected files and the plugin folder: missing, changed and extra paths. */
export function drift(root = ROOT) {
  const { files, archive } = expected(root);
  const dest = join(root, DEST);
  const onDisk = walk(dest).filter((p) => archive || !p.startsWith(`${ARCHIVE}/`));
  const out = [];
  for (const [path, text] of files) {
    const p = join(dest, path);
    if (!existsSync(p)) out.push(`missing ${path}`);
    else if (readFileSync(p, "utf8") !== text) out.push(`changed ${path}`);
  }
  for (const path of onDisk) if (!files.has(path)) out.push(`extra ${path}`);
  return { drift: out, archive, count: files.size };
}

export function write(root = ROOT) {
  const { files, archive } = expected(root);
  const dest = join(root, DEST);
  for (const path of walk(dest)) {
    if (!files.has(path) && (archive || !path.startsWith(`${ARCHIVE}/`))) rmSync(join(dest, path));
  }
  for (const [path, text] of files) {
    mkdirSync(dirname(join(dest, path)), { recursive: true });
    writeFileSync(join(dest, path), text);
  }
  return { count: files.size, archive };
}

function main(args) {
  const archiveLine = (a) => (a ? "owner archive copies included" : "owner archive absent, tracked copies only");
  if (args.includes("--check")) {
    const r = drift();
    if (r.drift.length > 0) {
      stdout.write(`plugin references drifted from ${SOURCE}; run node tools/plugin/build.mjs\n${r.drift.map((d) => `  ${d}`).join("\n")}\n`);
      return 1;
    }
    stdout.write(`plugin references clean: ${r.count} files, ${archiveLine(r.archive)}\n`);
    return 0;
  }
  const r = write();
  stdout.write(`plugin references written: ${r.count} files, ${archiveLine(r.archive)}\n`);
  return 0;
}

if (argv[1] && import.meta.url === pathToFileURL(resolve(argv[1])).href) exit(main(argv.slice(2)));
