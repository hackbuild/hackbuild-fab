// lint-plan-types: plan documents link to spec types and never copy their bodies
// (MILESTONES.md 1.5 and 3.7, card M-S-T01 in docs/plan/milestones/M-S-walking-skeleton.md).
// Collects every exported type and interface name from spec/*.ts, scans fenced code
// blocks in the plan docs, and reports a `type <Name> =`, `interface <Name>` or
// `<Name> {` declaration whose name is a spec export.
// Usage:
//   node tools/lint-plan-types.mjs [--warn] [--spec <dir>] [--report <file>] [<path>...]
// Paths default to docs/plan and docs/plan/milestones (Markdown files, not recursive).
// The hit list goes to tools/reports/plan-types.txt unless --report names another file.
// Exit 0 with no hit or under --warn, 1 on a hit, 2 on a usage error.
// Warn mode holds until the M00 exit; then CI drops --warn and the lint blocks.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, resolve, dirname, extname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Map of exported type or interface name to the spec file that declares it. */
export function specExports(specDir) {
  const names = new Map();
  const files = readdirSync(specDir).filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts")).sort();
  const rx = /^\s*export\s+(?:declare\s+)?(?:type|interface)\s+([A-Za-z_$][\w$]*)/gm;
  for (const f of files) {
    const text = readFileSync(join(specDir, f), "utf8");
    for (const m of text.matchAll(rx)) if (!names.has(m[1])) names.set(m[1], f);
  }
  return names;
}

const FENCE = /^\s{0,3}(`{3,}|~{3,})/;
const GENERIC = String.raw`(?:<[^>{}=]*(?:<[^>{}]*>[^>{}=]*)*>)?`;
const PATTERNS = [
  new RegExp(String.raw`\btype\s+([A-Za-z_$][\w$]*)\s*${GENERIC}\s*=`, "g"),
  new RegExp(String.raw`\binterface\s+([A-Za-z_$][\w$]*)\b`, "g"),
  // a bare shape heading a line: `CheckResult {` or `export CheckResult<T> {`
  new RegExp(String.raw`^\s*(?:export\s+)?([A-Za-z_$][\w$]*)\s*${GENERIC}\s*\{`, "g"),
];

/** Hits in one Markdown text: { line, name } per declaration of a spec export inside a fence. */
export function scanText(text, names) {
  const hits = [];
  let open = null;
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const f = FENCE.exec(line);
    if (f) {
      if (open === null) open = f[1];
      else if (f[1][0] === open[0] && f[1].length >= open.length && line.trim() === f[1]) open = null;
      continue;
    }
    if (open === null) continue;
    const seen = new Set();
    for (const rx of PATTERNS) {
      rx.lastIndex = 0;
      for (const m of line.matchAll(rx)) {
        if (names.has(m[1]) && !seen.has(m[1])) {
          seen.add(m[1]);
          hits.push({ line: i + 1, name: m[1] });
        }
      }
    }
  }
  return hits;
}

function markdownFiles(paths) {
  const out = [];
  for (const p of paths) {
    if (!existsSync(p)) throw new Error(`no such path: ${p}`);
    if (statSync(p).isDirectory()) {
      for (const f of readdirSync(p).sort()) {
        const full = join(p, f);
        if (statSync(full).isFile() && extname(f) === ".md") out.push(full);
      }
    } else out.push(p);
  }
  return out;
}

export function lint({ specDir, paths }) {
  const names = specExports(specDir);
  const docs = markdownFiles(paths);
  const hits = [];
  for (const file of docs) {
    for (const h of scanText(readFileSync(file, "utf8"), names)) {
      hits.push({ file: relative(REPO, resolve(file)), line: h.line, name: h.name, spec: `spec/${names.get(h.name)}` });
    }
  }
  return { hits, docs: docs.length, exports: names.size };
}

export function formatReport({ hits, docs, exports }) {
  const body = hits.map((h) => `${h.file}:${h.line} ${h.name} ${h.spec}`);
  return [
    "# plan-types: spec type declarations copied into plan docs",
    "# generated by node tools/lint-plan-types.mjs; never hand-edit",
    `# ${hits.length} hits over ${docs} docs, ${exports} spec exports (computed)`,
    "# file:line name spec-file; replace each hit with a link `spec/<file>.ts` (`<Name>`)",
    ...body,
    "",
  ].join("\n");
}

function main(argv) {
  let warn = false;
  let specDir = join(REPO, "spec");
  let report = join(REPO, "tools/reports/plan-types.txt");
  const paths = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--warn") warn = true;
    else if (a === "--spec") specDir = resolve(argv[++i] ?? "");
    else if (a === "--report") report = resolve(argv[++i] ?? "");
    else if (a.startsWith("--")) {
      process.stderr.write(`lint-plan-types: unknown flag ${a}\n`);
      return 2;
    } else paths.push(resolve(a));
  }
  if (paths.length === 0) paths.push(join(REPO, "docs/plan"), join(REPO, "docs/plan/milestones"));
  let result;
  try {
    result = lint({ specDir, paths });
  } catch (e) {
    process.stderr.write(`lint-plan-types: ${e.message}\n`);
    return 2;
  }
  mkdirSync(dirname(report), { recursive: true });
  writeFileSync(report, formatReport(result));
  for (const h of result.hits) process.stdout.write(`${h.file}:${h.line} ${h.name} ${h.spec}\n`);
  const rel = relative(REPO, report);
  const where = rel && !rel.startsWith("..") ? rel : report;
  process.stdout.write(
    `lint-plan-types: ${result.hits.length} hits over ${result.docs} docs (computed), list in ${where}${warn ? ", warn mode" : ""}\n`,
  );
  return result.hits.length > 0 && !warn ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exitCode = main(process.argv.slice(2));
