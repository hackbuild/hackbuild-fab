// THIRD-PARTY-NOTICES.txt from the bake licence manifests (LICENSING.md
// 1.2): every package any bake.json inlines, from licenceManifest (the
// generator bake.mjs runs), with its name, version, audited licence, the
// copyright line of its LICENSE file, its NOTICE text verbatim for an
// Apache-2.0 item, the source location for an LGPL or MPL item, then each
// licence's full text once. Deterministic: sorted, no date, LF endings.
// Run through `node tools/licences.mjs --notices [--check]`.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { bundleEntry, findManifests, packageOf, REPO, resolveFrom } from './bake.mjs';
import { licenceManifest, npmSources, readTable } from './licence-manifest.mjs';

export const NOTICES = 'THIRD-PARTY-NOTICES.txt';
const SPDX = /\b(MIT|Apache-2\.0|OFL-1\.1|CC-BY-4\.0|BSD-[23]-Clause|ISC|MPL-2\.0|LGPL-[0-9.]+(?:-or-later|-only)?)\b/g;

const firstFile = (root, names) => names.map((n) => join(root, n)).find((p) => existsSync(p)) ?? null;
const lf = (s) => s.replace(/\r\n?/g, '\n').replace(/\s+$/, '');

/** Every package any bake inlines, with the folder it is installed in. */
async function inlinedEverywhere(repo) {
  const all = new Map();
  for (const mp of findManifests(repo)) {
    const m = JSON.parse(readFileSync(mp, 'utf8'));
    const base = dirname(mp);
    const pk = npmSources(m).map((f) => packageOf(resolveFrom(base, f))).filter((p) => p !== null);
    if (m.entry) pk.push(...(await bundleEntry(resolve(base, m.entry))).inlined);
    for (const p of pk) if (!all.has(`${p.name}@${p.version}`)) all.set(`${p.name}@${p.version}`, p);
  }
  return [...all.values()];
}

export async function generate(repo = REPO) {
  const pkgs = await inlinedEverywhere(repo);
  const { rows, problems } = licenceManifest(pkgs, readTable(repo));
  if (problems.length > 0) throw new Error(problems.join('; '));
  const where = new Map(pkgs.map((p) => [`${p.name}@${p.version}`, p.root]));
  const texts = new Map();
  const out = [
    'THIRD-PARTY-NOTICES.txt',
    '',
    'Third-party software inlined in the hackbuild-fab bakes (dist/bench, dist/kit, dist/legacy).',
    'Generated by node tools/licences.mjs --notices from tools/licences.json and the installed',
    'LICENSE and NOTICE files. Regenerate it; never edit it by hand.',
    '',
  ];
  for (const r of rows) {
    const root = where.get(`${r.name}@${r.version}`);
    const lic = firstFile(root, ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE', 'OFL.txt']);
    const body = lic === null ? '' : lf(readFileSync(lic, 'utf8'));
    const copyright = body.split('\n').map((l) => l.trim()).find((l) => /^copyright\b/i.test(l)) ?? 'no copyright line in the package licence file';
    out.push(`${r.name} ${r.version}`, `  licence: ${r.audited}`, `  copyright: ${copyright.length > 200 ? `${copyright.slice(0, 200).replace(/\s+\S*$/, '')} ...` : copyright}`);
    const ids = [...new Set([...(r.audited ?? '').matchAll(SPDX)].map((x) => x[1]))];
    if (ids.includes('Apache-2.0')) {
      const notice = firstFile(root, ['NOTICE', 'NOTICE.md', 'NOTICE.txt']);
      out.push(notice === null ? '  notice: none shipped' : `  notice:\n${lf(readFileSync(notice, 'utf8')).split('\n').map((l) => `    ${l}`).join('\n')}`);
    }
    if (ids.some((x) => /^(LGPL|MPL)/.test(x))) {
      const pj = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
      out.push(`  source: ${typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? 'not stated in package.json'}`);
    }
    out.push('');
    for (const id of ids) {
      if (texts.has(id)) continue;
      const own = join(repo, 'LICENSES', `${id}.txt`);
      if (existsSync(own)) texts.set(id, lf(readFileSync(own, 'utf8')));
      else if (ids.length === 1 && body !== '') texts.set(id, body);
    }
  }
  out.push('Licence texts, each once', '');
  for (const id of [...texts.keys()].sort()) out.push(`${id}`, '', texts.get(id), '');
  return `${out.join('\n').replace(/\s+$/, '')}\n`;
}

/** Writes the file, or with check compares it; returns the exit code. */
export async function notices({ check = false, repo = REPO } = {}) {
  const text = await generate(repo);
  const file = join(repo, NOTICES);
  if (check) {
    const now = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (now !== text) {
      console.log(`licences: fail ${NOTICES} differs from a fresh generation; run node tools/licences.mjs --notices`);
      return 1;
    }
    console.log(`licences: ${NOTICES} matches a fresh generation`);
    return 0;
  }
  writeFileSync(file, text);
  console.log(`licences: wrote ${NOTICES}, ${text.split('\n').length} lines`);
  return 0;
}
