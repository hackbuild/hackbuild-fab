// Gathers packages/checks/seed/checks/<ID>.json into checks.seed.json and
// writes the check module index packages/checks/src/defs/index.ts.
// Rule: a new check adds packages/checks/seed/checks/<ID>.json (one seed row,
// file name equal to its id) and packages/checks/src/defs/<fam>/<ID>.ts, then
// runs npm run registries; never edit checks.seed.json, index.ts or the order
// list in _head.json by hand. _head.json holds note, candidates and order:
// the ids in the append order the seed had when it was split, frozen. Rows
// in order come first in that order, every later row follows sorted by id.

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { frozenThenSorted, jsonText, readFragments } from "../lib.mjs";

export const name = "checks";

const SEED_DIR = "packages/checks/seed/checks";
const DEFS_DIR = "packages/checks/src/defs";
const HEAD = "_head";

function parse(file, text) {
  try {
    return JSON.parse(text);
  } catch (e) {
    throw new Error(`${file} is not JSON: ${e.message}`);
  }
}

// The gathered seed object: note, checks in head order then sorted, then
// candidates. Throws on a missing or malformed head, a fragment that is not
// one row object, or a row whose id is not its file name.
export function gatherSeed(root) {
  const dir = join(root, SEED_DIR);
  const frags = readFragments(dir, ".json");
  const headFrag = frags.find((f) => f.id === HEAD);
  if (headFrag === undefined) throw new Error(`no ${SEED_DIR}/${HEAD}.json holding note, candidates and order`);
  const head = parse(`${SEED_DIR}/${HEAD}.json`, headFrag.text);
  if (!Array.isArray(head?.order) || head.order.some((id) => typeof id !== "string")) throw new Error(`${SEED_DIR}/${HEAD}.json has no order array of ids`);
  if (new Set(head.order).size !== head.order.length) throw new Error(`${SEED_DIR}/${HEAD}.json lists an id twice in order`);
  const rows = new Map();
  for (const frag of frags) {
    if (frag.id === HEAD) continue;
    const file = `${SEED_DIR}/${frag.id}.json`;
    const row = parse(file, frag.text);
    if (row === null || typeof row !== "object" || Array.isArray(row)) throw new Error(`${file} holds no seed row object`);
    if (row.id !== frag.id) throw new Error(`${file} holds ${row.id}. name the file ${SEED_DIR}/${row.id}.json`);
    rows.set(row.id, row);
  }
  const ids = frozenThenSorted([...rows.keys()], head.order);
  const seed = {};
  if (head.note !== undefined) seed.note = head.note;
  seed.checks = ids.map((id) => rows.get(id));
  if (head.candidates !== undefined) seed.candidates = head.candidates;
  return seed;
}

// Every defs/<dir>/CHK-<FAM>-<NN>.ts, sorted by path, as import entries.
// Throws on a module whose directory is not its family in lower case.
export function checkModules(root) {
  const defs = join(root, DEFS_DIR);
  const out = [];
  const dirs = readdirSync(defs, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  for (const dir of dirs) {
    for (const file of readdirSync(join(defs, dir)).filter((f) => /^CHK-.*\.ts$/.test(f)).sort()) {
      const m = /^CHK-([A-Z0-9]+)-(\d+)\.ts$/.exec(file);
      if (m === null) throw new Error(`${DEFS_DIR}/${dir}/${file} is not named CHK-<FAM>-<NN>.ts`);
      if (m[1].toLowerCase() !== dir) throw new Error(`${DEFS_DIR}/${dir}/${file} sits outside its family directory ${m[1].toLowerCase()}`);
      out.push({ name: `c${m[1].toLowerCase()}${m[2]}`, from: `./${dir}/${file.slice(0, -3)}.js` });
    }
  }
  return out;
}

// Names packed into lines of at most width columns, indented two spaces.
function wrap(names, width = 80) {
  const lines = [];
  let line = "";
  for (const n of names) {
    const next = line === "" ? `  ${n},` : `${line} ${n},`;
    if (line !== "" && next.length > width) {
      lines.push(line);
      line = `  ${n},`;
    } else {
      line = next;
    }
  }
  if (line !== "") lines.push(line);
  return lines;
}

export function indexText(root) {
  const mods = checkModules(root);
  return [
    "// Every check module, one per seeded check id. registerChecks joins this",
    "// list with the seed and refuses a seed row without a module or a module",
    "// without a row (registry.test.ts), so the list cannot drift from the seed.",
    "// Generated by tools/gen/registries/checks.mjs from defs/*/CHK-*.ts; add a",
    "// module file and run npm run registries, never edit this file by hand.",
    "",
    'import type { AnyCheckModule } from "../registry.js";',
    ...mods.map((m) => `import { check as ${m.name} } from "${m.from}";`),
    "",
    "export const CHECK_MODULES: readonly AnyCheckModule[] = [",
    ...wrap(mods.map((m) => m.name)),
    "];",
    "",
  ].join("\n");
}

export function outputs(root) {
  return [
    { path: "packages/checks/seed/checks.seed.json", text: jsonText(gatherSeed(root)) },
    { path: `${DEFS_DIR}/index.ts`, text: indexText(root) },
  ];
}
