// The def files of dir in file name order, each with its exported const.
// Throws naming the file when it exports no single const of the def type.
export function defEntries(root, dir, type) {
  return readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.startsWith("."))
    .sort()
    .map((f) => {
      let name;
      try {
        name = exportedConst(readFileSync(join(root, dir, f), "utf8"), type);
      } catch (e) {
        throw new Error(`${dir}/${f}: ${e.message}`);
      }
      return { name, from: `./${f.slice(0, -3)}.js` };
    });
}

export function indexText(root, ix) {
  const defs = defEntries(root, ix.dir, ix.type);
  const lines = [
    ...ix.header.map((l) => `// ${l}`),
    "",
    `import type { ${ix.type} } from "@hackbuild/spec";`,
    ...defs.map((d) => `import { ${d.name} } from "${d.from}";`),
    ...ix.spreads.map((s) => `import { ${s.name} } from "${s.from}";`),
    "",
    `export const ${ix.list}: readonly ${ix.type}[] = [`,
    ...defs.map((d) => `  ${d.name},`),
    ...ix.spreads.flatMap((s) => [...(s.comment === null ? [] : [`  // ${s.comment}`]), `  ...${s.name},`]),
    "];",
  ];
  if (ix.ids !== undefined) {
    lines.push("", "/** The ids, for added.ts. */", `export const ${ix.ids}: readonly string[] = ${ix.list}.map((d) => d.id);`);
  }
  return lines.join("\n") + "\n";
}

export function outputs(root) {
  return INDEXES.filter((ix) => existsSync(join(root, ix.dir))).map((ix) => ({ path: `${ix.dir}/index.ts`, text: indexText(root, ix) }));
}
