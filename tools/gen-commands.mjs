#!/usr/bin/env node
// Writes packages/commands/src/defs/index.ts: one import per def file in
// that directory, in file name order, and SPECS listing them. A command
// lands by adding its def file and rerunning this, never by editing the
// list. --check writes nothing and exits 1 when the committed index
// differs from what the directory gives.
//
// node tools/gen-commands.mjs [--check] [--dir=<defs dir>]

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const check = args.includes("--check");
const dirArg = args.find((a) => a.startsWith("--dir="));
const dir = resolve(dirArg ? dirArg.slice("--dir=".length) : join(fileURLToPath(import.meta.url), "..", "..", "packages", "commands", "src", "defs"));
const target = join(dir, "index.ts");

const ident = (file) => file.replace(/\.ts$/, "").replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function indexText(files) {
  const names = files.filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
  return [
    "// generated by tools/gen-commands.mjs, do not edit: one import per def",
    "// file in this directory, in file name order.",
    "",
    'import type { AnySpec } from "../spec.js";',
    ...names.map((f) => `import { spec as ${ident(f)} } from "./${f.replace(/\.ts$/, ".js")}";`),
    "",
    "/** Every command spec, one per def file. */",
    "export const SPECS: readonly AnySpec[] = [",
    ...names.map((f) => `  ${ident(f)},`),
    "];",
    "",
  ].join("\n");
}

const want = indexText(readdirSync(dir));
let have = null;
try { have = readFileSync(target, "utf8"); } catch { have = null; }
if (check) {
  if (have !== want) {
    console.log(`gen-commands: fail ${target} differs from the def files; run node tools/gen-commands.mjs`);
    process.exit(1);
  }
  console.log("gen-commands: ok");
} else if (have !== want) {
  writeFileSync(target, want);
  console.log(`gen-commands: wrote ${target}`);
} else {
  console.log("gen-commands: unchanged");
}
