#!/usr/bin/env node
// Writes packages/catalog/data/modules/<id>/pins.json for every module row
// whose pins parse from KiCad files at load (row.json fields.pins.from), so a
// kernel package that cannot read files (archetypes, tier 1) imports the
// resolved pin table as JSON, as it imports rp2040-zero.json. The table is
// catalogPins over the built catalog; packages/catalog/test/resolved-pins
// holds each file equal to a fresh parse.
//
//   node tools/catalog/resolve-pins.mjs           write every stale file
//   node tools/catalog/resolve-pins.mjs --check   exit 1 naming each stale file
//
// Reads packages/catalog/dist: run tsc -b first.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const DATA = path.join(ROOT, "packages", "catalog", "data");
const check = process.argv.includes("--check");

const { KICAD_RESOLVERS, catalogPins, loadCatalog } = await import(pathToFileURL(path.join(ROOT, "packages", "catalog", "dist", "src", "index.js")).href);

const files = new Map();
const walk = (d) => {
  for (const n of readdirSync(d)) {
    const p = path.join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else files.set(path.relative(DATA, p).split(path.sep).join("/"), new Uint8Array(readFileSync(p)));
  }
};
walk(DATA);
const catalog = loadCatalog(files, { resolvers: KICAD_RESOLVERS });

/** The text of one resolved table: stable key order, two space indent, a trailing newline. */
function pinsText(id, mcu, out) {
  return `${JSON.stringify({
    id,
    mcu,
    note: `generated by tools/catalog/resolve-pins.mjs from modules/${id}/row.json; never edited by hand. Pins in the row frame, mm.`,
    pins: out.pins.map((q) => ({ n: q.n, name: q.name, role: q.role, at: q.at })),
  }, null, 2)}\n`;
}

let stale = 0;
for (const dir of readdirSync(path.join(DATA, "modules"))) {
  const rowFile = path.join(DATA, "modules", dir, "row.json");
  if (!existsSync(rowFile)) continue;
  const row = JSON.parse(readFileSync(rowFile, "utf8"));
  if (row.fields?.pins?.from === undefined) continue;
  const target = path.join(DATA, "modules", dir, "pins.json");
  const text = pinsText(row.id, row.mcu ?? null, catalogPins(catalog, row.id));
  const have = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (have === text) continue;
  stale += 1;
  if (check) console.error(`resolve-pins: ${path.relative(ROOT, target)} is stale; run node tools/catalog/resolve-pins.mjs`);
  else { writeFileSync(target, text); console.log(`resolve-pins: wrote ${path.relative(ROOT, target)}`); }
}
if (check && stale > 0) process.exit(1);
if (stale === 0) console.log("resolve-pins: every table fresh");
