// Writes the generated blocks of reference/electrical/pip-drive/chase.ts:
// its hookup and its scene.drive (M05-T11). The key paths are PIP's
// (packages/circuit/test/fixtures/pip-b137deb-elec.json, dumped from PIP
// b137deb by tools/legacy/pip/dump-elec.mjs): switch posts, declared
// contact resistance, common net and pin per key. The trace lengths and
// via counts are this package's route of the same default layout
// (packages/copper/test/fixtures/pip-b137deb-route.json) in its public
// default mode, Float64 history (M05-T08), lengths with the terminal
// stubs as PIP's netLen sums them (src/model.js line 386). The stack
// heights, trace width and thickness come from profile (traceStack and
// the stack rows) and must equal the heights PIP priced its posts at.
//
// A chase is a literal and computes nothing (D-178), so the numbers are
// written into it between the `generated by` markers; the reference test
// reruns sceneDrive() and fails when the chase differs.
//
//   node packages/copper/scripts/pip-drive-scene.mjs           print the blocks
//   node packages/copper/scripts/pip-drive-scene.mjs --write   write them into chase.ts
//
// Run `npx tsc -b packages/copper` first; the script reads dist/ and
// resolves the spec sources through core's resolve hook.

import { readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";

const here = (p) => new URL(p, import.meta.url);
register(here("../../../core/dist/resolve-hook.js"));
const { createProfileLookup, loadProfile } = await import("@hackbuild/profile");
const copper = await import(here("../dist/index.js").href);

const CHASE = here("../../../reference/electrical/pip-drive/chase.ts");
export const ELEC = "packages/circuit/test/fixtures/pip-b137deb-elec.json";
export const ROUTE = "packages/copper/test/fixtures/pip-b137deb-route.json";
/** The ffc5p preset layer; the stack heights follow PIP's 0.24 grid as pip-buried-route builds them. */
const MACHINE = "ffc5p";
/** Pins and the read of each key as the emitted firmware reads it: keys drive high and wait KEY_WAIT_US, touch drives low and waits TOUCH_WAIT_US (pip_stick.ino:25, :31, :55 to :64). */
const READ = {
  key: { model: "charge-release", drive: "high", driveUs: 30, waitUs: 3500, waitSource: "default" },
  touch: { model: "charge-release", drive: "low", driveUs: 30, waitUs: 1500, waitSource: "default" },
};
/** PIP's rhoT row, the bulk row its Rsw is computed over (layout.js:46, profile ctpu.pip.bulk). */
const CONTACT_MATERIAL = "ctpu";
const SWITCH_LINES = { flex: "line 404", clicky: "line 407", touch: "line 413", stick: "line 411" };

const read = (p) => JSON.parse(readFileSync(here(`../../../${p}`), "utf8"));

/** The hookup and scene.drive the chase declares, from the fixtures, this package's route and profile. */
export function sceneDrive() {
  const el = read(ELEC);
  const fx = read(ROUTE);
  const profile = createProfileLookup(loadProfile());
  const s = fx.input.route;
  const r = copper.route({ outline: fx.input.outline, nets: fx.input.nets, settings: { w: s.w, clr: s.clr, grid: s.grid, via: s.via, margin: s.margin, iters: s.iters } }, profile);
  if (r.conflicts !== 0 || r.unrouted !== 0) throw new Error(`default route has ${r.conflicts} conflicts and ${r.unrouted} unrouted terminals; the drive reads a clean route`);
  const z = copper.traceStack(profile, profile.preset(MACHINE).layer);
  const width = profile.constant("stack.traceWidth").value;
  const t = profile.constant("stack.trace").value;
  const terminal = { hMm: z.floor - z.l1[0], rMm: s.post };
  const via = { hMm: z.l2[1] - z.l1[0], rMm: s.via };
  const same = (what, ours, pip) => { if (ours !== pip) throw new Error(`${what}: profile gives ${ours}, PIP priced ${pip}`); };
  same("trace width", width, el.route.w);
  same("trace thickness", t, el.stack.trace);
  same("terminal post height", terminal.hMm, el.stack.hPost);
  same("via height", via.hMm, el.stack.viaH);
  same("terminal post radius", terminal.rMm, el.route.post);
  same("via radius", via.rMm, el.route.via);
  const hyp = (q) => Math.hypot(q[1][0] - q[0][0], q[1][1] - q[0][1]);
  const rails = { GND: "gnd", "3V3": "power" };
  const nets = r.nets.map((n) => ({
    net: n.name, lengthMm: n.len + n.stubs.reduce((a, q) => a + hyp(q), 0), terminalPosts: 2, vias: n.vias.length,
    ...(n.name in rails ? { rail: rails[n.name] } : {}),
  }));
  const keys = el.keys.map((k) => {
    for (const p of k.posts.slice(0, 2)) {
      const want = p.what === "terminal" ? terminal : via;
      same(`${k.id} ${p.what} post`, `${want.hMm} ${want.rMm}`, `${p.hMm} ${p.rMm}`);
    }
    if (k.posts[0].count !== 2) throw new Error(`${k.id}: PIP priced ${k.posts[0].count} terminal posts, the scene declares 2`);
    return {
      port: `port.${k.id}`, interface: k.type === "touch" ? "touch" : "digital", net: k.net, return: k.common,
      posts: k.posts.filter((p) => p.what === "switch").map((p) => ({ id: `switch.${k.id}`, hMm: p.hMm, rMm: p.rMm, count: p.count })),
      contactOhm: k.RswOhm,
      ...(k.RswOhm > 0 ? { contactMaterial: CONTACT_MATERIAL } : {}),
      contactSource: k.RswOhm > 0
        ? `pip-controller src/model.js ${SWITCH_LINES[k.type]} at b137deb, computed by PIP over rhoT 400 ohm cm (${ELEC})`
        : `pip-controller src/model.js ${SWITCH_LINES[k.type]} at b137deb: no switch contact`,
    };
  });
  const hookup = el.keys.map((k) => ({ port: `port.${k.id}`, mcu: "rp2040", pin: k.pin, read: k.type === "touch" ? READ.touch : READ.key }));
  return {
    hookup,
    drive: {
      material: "cpla",
      trace: { widthMm: width, tMm: t },
      terminal,
      via,
      route: `packages/copper route() default mode over ${ROUTE}: conflicts ${r.conflicts}, unrouted ${r.unrouted}, iters ${r.iters}; lengths with stubs`,
      nets,
      keys,
      shipped: { keyWaitUs: 200, source: "pip-controller firmware/pip/pip.ino:20 (D-080)" },
    },
  };
}

/** A value as chase source: object keys bare, strings double quoted, numbers in their shortest round trip form. */
function lit(v, ind) {
  const pad = " ".repeat(ind);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== "object")) return `[${v.map((x) => lit(x, 0)).join(", ")}]`;
    return `[\n${v.map((x) => `${pad}  ${lit(x, ind + 2)},`).join("\n")}\n${pad}]`;
  }
  if (v !== null && typeof v === "object") {
    const parts = Object.entries(v).map(([k, x]) => `${/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k)}: ${lit(x, ind)}`);
    const flat = `{ ${parts.join(", ")} }`;
    if (flat.length + ind <= 150 && !flat.includes("\n")) return flat;
    return `{\n${Object.entries(v).map(([k, x]) => `${pad}  ${/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k)}: ${lit(x, ind + 2)},`).join("\n")}\n${pad}}`;
  }
  return JSON.stringify(v);
}

const BEGIN = "  // generated by node packages/copper/scripts/pip-drive-scene.mjs --write: begin";
const END = "  // generated by node packages/copper/scripts/pip-drive-scene.mjs --write: end";

/** The text between the markers. */
export function blockText(s) {
  return [`  hookup: ${lit(s.hookup, 2)},`, `  scene: {`, `    nets: "contact",`, `    drive: ${lit(s.drive, 4)},`, `  },`].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = blockText(sceneDrive());
  if (process.argv.includes("--write")) {
    const src = readFileSync(CHASE, "utf8");
    const a = src.indexOf(BEGIN), b = src.indexOf(END);
    if (a < 0 || b < a) throw new Error("chase.ts has no generated markers");
    writeFileSync(CHASE, `${src.slice(0, a + BEGIN.length)}\n${text}\n${src.slice(b)}`);
    process.stdout.write(`pip-drive-scene: wrote ${CHASE.pathname}\n`);
  } else {
    process.stdout.write(`${text}\n`);
  }
}
